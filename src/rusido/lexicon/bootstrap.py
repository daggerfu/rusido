def _noun_entry(lemma: str) -> LexiconEntry:
    w = lemma
    if w.endswith("ь"):
        return LexiconEntry(w, w[:-1], POS_NOUN, stem_type=STEM_PALATAL)
    for suf in ("ия", "ие", "а", "я", "о", "е", "ы", "и", "у"):
        if w.endswith(suf) and len(w) > len(suf) + 2:
            return LexiconEntry(w, w[: -len(suf)], POS_NOUN)
    return LexiconEntry(w, w, POS_NOUN)


def _verb_entry(lemma: str) -> LexiconEntry:
    if lemma.endswith("ти"):  # уже русидо-инфинитив (войти → вой-)
        return LexiconEntry(lemma, lemma[:-2], POS_VERB,
                            source_form=lemma)
    stem = lemma[:-2] if lemma.endswith("ть") else lemma
    return LexiconEntry(lemma, stem, POS_VERB,
                        source_form=stem + "ти")


def _adjective_entry(lemma: str) -> LexiconEntry:
    stem = lemma[:-2] if lemma.endswith(("ый", "ий", "ой")) else lemma
    return LexiconEntry(lemma, stem, POS_ADJ)


def bootstrap_entries() -> list[LexiconEntry]:
    """Новые записи лексикона (без дублей лемм базового списка)."""
    entries: list[LexiconEntry] = []
    for lemma in _NOUNS:
        entries.append(_noun_entry(lemma))
    for lemma in _VERBS:
        if lemma.endswith(("ть", "ти")):
            entries.append(_verb_entry(lemma))
    for lemma in _ADJECTIVES:
        entries.append(_adjective_entry(lemma))
    return entries
